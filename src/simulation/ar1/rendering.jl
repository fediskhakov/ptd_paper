    )
end

function _table_content_fingerprint(tables)
    identities = [(;
        id=Symbol(_ar1_render_field(table, :id, "table")),
        filename=String(_ar1_render_field(table, :filename, "table")),
        row_fingerprint=String(_ar1_render_field(
            table, :row_fingerprint, "table")),
        bytes=Int(_ar1_render_field(table, :bytes, "table")),
        sha256=String(_ar1_render_field(table, :sha256, "table")),
    ) for table in tables]
    return stable_fingerprint(identities)
end

