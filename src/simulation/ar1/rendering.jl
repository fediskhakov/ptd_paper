function _ar1_render_write_manifest(path::AbstractString, artifact::AbstractDict;
                         compress::Bool)
    JLD2.jldopen(path, "w"; compress) do file
        for (name, value) in pairs(artifact)
            file[String(name)] = value
        end
    end
    return path
end

function _ar1_render_load_jld2(path::AbstractString)
    isfile(path) || throw(ArgumentError(
        "AR(1) render manifest does not exist: $path"))
    return JLD2.jldopen(path, "r") do file
        Dict{String,Any}(String(name) => file[String(name)]
                         for name in keys(file))
    end
end

function _ar1_render_validate_manifest(artifact, directory::AbstractString)
    artifact isa AbstractDict || throw(ArgumentError(
        "AR(1) render manifest must be a dictionary"))
    metadata = _ar1_render_field(artifact, :metadata)
    String(_ar1_render_field(metadata, :artifact_schema, "metadata")) ==
        AR1_RENDER_CONTEST_SCHEMA_VERSION || throw(ArgumentError(
            "AR(1) render schema mismatch"))
    _ar1_render_field(metadata, :status, "metadata") === :complete ||
        throw(ArgumentError("AR(1) render manifest is incomplete"))
    completed = String(_ar1_render_field(metadata, :completed_utc, "metadata"))
    !isempty(completed) && endswith(completed, 'Z') || throw(ArgumentError(
        "AR(1) render completion timestamp is invalid"))

    source = _ar1_render_field(artifact, :source_provenance)
    _ar1_render_field(source, :status, "source_provenance") === :authenticated &&
        String(_ar1_render_field(source, :artifact_schema, "source_provenance")) ==
            AR1_CONTEST_ARTIFACT_SCHEMA_VERSION || throw(ArgumentError(
                "AR(1) render source is not an authenticated AR(1) artifact"))
    stable_fingerprint(source) == String(_ar1_render_field(metadata,
        :source_provenance_fingerprint, "metadata")) ||
        throw(ArgumentError("AR(1) source provenance fingerprint mismatch"))
    _source_identity(source) == String(_ar1_render_field(metadata,
        :source_identity_fingerprint, "metadata")) ||
        throw(ArgumentError("AR(1) source identity fingerprint mismatch"))
    _ar1_render_field(metadata, :source_status, "metadata") === :authenticated &&
        String(_ar1_render_field(metadata, :source_artifact_schema, "metadata")) ==
            AR1_CONTEST_ARTIFACT_SCHEMA_VERSION &&
        String(_ar1_render_field(metadata, :source_run_fingerprint, "metadata")) ==
            String(_ar1_render_field(source, :run_fingerprint, "source_provenance")) &&
        String(_ar1_render_field(metadata, :source_result_fingerprint, "metadata")) ==
            String(_ar1_render_field(source, :result_fingerprint, "source_provenance")) &&
        String(_ar1_render_field(metadata, :source_authentication_fingerprint,
            "metadata")) == String(_ar1_render_field(source,
            :authentication_fingerprint, "source_provenance")) ||
        throw(ArgumentError("AR(1) render metadata disagrees with source"))

    simulation = _ar1_render_field(artifact, :simulation_metadata)
    stable_fingerprint(simulation) == String(_ar1_render_field(metadata,
        :simulation_metadata_fingerprint, "metadata")) ==
        String(_ar1_render_field(source, :simulation_metadata_fingerprint,
            "source_provenance")) || throw(ArgumentError(
                "AR(1) render simulation metadata mismatch"))
    configuration = _ar1_render_field(artifact, :render_configuration)
    String(_ar1_render_field(configuration, :schema, "render_configuration")) ==
        AR1_RENDER_CONFIGURATION_SCHEMA_VERSION || throw(ArgumentError(
            "AR(1) render configuration schema mismatch"))
    stable_fingerprint(configuration) == String(_ar1_render_field(metadata,
        :render_configuration_fingerprint, "metadata")) ||
        throw(ArgumentError("AR(1) render configuration mismatch"))
    methods = Symbol.(collect(_ar1_render_field(
        configuration, :methods, "render_configuration")))
    panels = Symbol.(collect(_ar1_render_field(
        configuration, :panels, "render_configuration")))
    methods == [:ptd_sceq, :ptd_osa, :g2egm] && panels == [:ar1] ||
        throw(ArgumentError("AR(1) render methods or panels mismatch"))
    _ar1_render_field(configuration, :calibration, "render_configuration") ==
        (rho=0.9, sigma=0.1, initial_income=1.0) || throw(ArgumentError(
            "AR(1) render calibration mismatch"))
    String(_ar1_render_field(configuration, :environment_label,
        "render_configuration")) == AR1_ENVIRONMENT_LABEL ||
        throw(ArgumentError("AR(1) render environment label mismatch"))
    _ar1_render_field(_ar1_render_field(configuration, :method_display,
        "render_configuration"), :g2egm,
        "render_configuration.method_display") == "G2EGM" ||
        throw(ArgumentError("AR(1) G2EGM display label mismatch"))
    confidence_level = Float64(_ar1_render_field(configuration,
        :paired_confidence_level, "render_configuration"))

    outcome_rows = _ar1_render_field(artifact, :outcome_rows)
    ce_rows = _ar1_render_field(artifact, :ce_gap_rows)
    timing_rows = _ar1_render_field(artifact, :timing_rows)
    IID._validate_rows(outcome_rows, ce_rows, timing_rows,
        methods, panels, confidence_level)
    stable_fingerprint(outcome_rows) == String(_ar1_render_field(metadata,
        :outcome_rows_fingerprint, "metadata")) || throw(ArgumentError(
            "AR(1) outcome-row fingerprint mismatch"))
    stable_fingerprint(ce_rows) == String(_ar1_render_field(metadata,
        :ce_gap_rows_fingerprint, "metadata")) || throw(ArgumentError(
            "AR(1) CEG-row fingerprint mismatch"))
    stable_fingerprint(timing_rows) == String(_ar1_render_field(metadata,
        :timing_rows_fingerprint, "metadata")) || throw(ArgumentError(
            "AR(1) timing-row fingerprint mismatch"))

    tables = _ar1_render_field(artifact, :tables)
    expected_ids = Set((:outcome_shares, :ce_gaps, :timings))
    length(tables) == 3 && Set(Symbol(_ar1_render_field(table, :id, "table"))
        for table in tables) == expected_ids || throw(ArgumentError(
            "AR(1) render manifest requires exactly three tables"))
    table_files = _ar1_render_field(configuration, :table_files,
        "render_configuration")
    expected_filenames = Dict(
        :outcome_shares => String(_ar1_render_field(
            table_files, :outcome_shares, "table_files")),
        :ce_gaps => String(_ar1_render_field(table_files, :ce_gaps, "table_files")),
        :timings => String(_ar1_render_field(table_files, :timings, "table_files")),
    )
    expected_rows = Dict(
        :outcome_shares => stable_fingerprint(outcome_rows),
        :ce_gaps => stable_fingerprint(ce_rows),
        :timings => stable_fingerprint(timing_rows),
    )
    for (index, table) in enumerate(tables)
        location = "tables[$index]"
        _ar1_render_field(table, :status, location) === :complete ||
            throw(ArgumentError("$location is incomplete"))
        id = Symbol(_ar1_render_field(table, :id, location))
        filename = String(_ar1_render_field(table, :filename, location))
        basename(filename) == filename && filename == expected_filenames[id] ||
            throw(ArgumentError("$location filename mismatch"))
        String(_ar1_render_field(table, :row_fingerprint, location)) ==
            expected_rows[id] || throw(ArgumentError(
                "$location row fingerprint mismatch"))
        String(_ar1_render_field(table, :completed_utc, location)) == completed ||
            throw(ArgumentError("$location timestamp mismatch"))
        table_path = joinpath(directory, filename)
        isfile(table_path) || throw(ArgumentError(
            "AR(1) rendered table is missing: $table_path"))
        filesize(table_path) == Int(_ar1_render_field(table, :bytes, location)) &&
            _ar1_render_sha256_file(table_path) == String(_ar1_render_field(
                table, :sha256, location)) || throw(ArgumentError(
                    "$location file authentication mismatch"))
    end
    stable_fingerprint(tables) == String(_ar1_render_field(metadata,
        :table_catalog_fingerprint, "metadata")) || throw(ArgumentError(
            "AR(1) table-catalog fingerprint mismatch"))
    table_content_fingerprint = _table_content_fingerprint(tables)
    table_content_fingerprint == String(_ar1_render_field(metadata,
        :table_content_fingerprint, "metadata")) || throw(ArgumentError(
            "AR(1) table-content fingerprint mismatch"))

    result_fingerprint = stable_fingerprint((;
        source_identity_fingerprint=String(_ar1_render_field(metadata,
            :source_identity_fingerprint, "metadata")),
        render_configuration_fingerprint=stable_fingerprint(configuration),
        outcome_rows_fingerprint=stable_fingerprint(outcome_rows),
        ce_gap_rows_fingerprint=stable_fingerprint(ce_rows),
        timing_rows_fingerprint=stable_fingerprint(timing_rows),
        table_content_fingerprint,
    ))
    result_fingerprint == String(_ar1_render_field(metadata,
        :result_fingerprint, "metadata")) || throw(ArgumentError(
            "AR(1) render result fingerprint mismatch"))
    _ar1_render_authentication(metadata) == String(_ar1_render_field(metadata,
        :authentication_fingerprint, "metadata")) || throw(ArgumentError(
            "AR(1) render authentication mismatch"))
    return artifact
end

"""Load and authenticate an AR(1) render manifest and its adjacent tables."""
function load_ar1_render_manifest(path::AbstractString)
    manifest_path = abspath(path)
    return _ar1_render_validate_manifest(
        _ar1_render_load_jld2(manifest_path), dirname(manifest_path))
end

"""Deterministic table directory for one processed AR(1) run."""
function ar1_render_output_directory(output_root::AbstractString,
                                     run_fingerprint::AbstractString)
    return joinpath(abspath(output_root),
        "configuration-$(String(run_fingerprint))")
end

function _ar1_render_publication_identity(metadata)
    return stable_fingerprint((;
        source_identity_fingerprint=String(_ar1_render_field(metadata,
            :source_identity_fingerprint, "metadata")),
        render_configuration_fingerprint=String(_ar1_render_field(metadata,
            :render_configuration_fingerprint, "metadata")),
        result_fingerprint=String(_ar1_render_field(metadata,
            :result_fingerprint, "metadata")),
    ))
end

function _reuse_or_refuse(destination::AbstractString, proposed)
    manifest_path = joinpath(destination, AR1_RENDER_MANIFEST_FILENAME)
    existing = try
        load_ar1_render_manifest(manifest_path)
    catch error
        throw(ArgumentError(
            "refusing to replace invalid AR(1) render output $destination: " *
            sprint(showerror, error)))
    end
    _ar1_render_publication_identity(_ar1_render_field(existing, :metadata,
        "existing render manifest")) ==
        _ar1_render_publication_identity(_ar1_render_field(proposed, :metadata,
            "proposed render manifest")) || throw(ArgumentError(
                "refusing to replace a different AR(1) render at $destination"))
    return existing
end

function _publish_directory(destination::AbstractString,
                            temporary::AbstractString, proposed)
    if isdir(destination)
        return (:reused, _reuse_or_refuse(destination, proposed))
    elseif ispath(destination)
        throw(ArgumentError(
            "AR(1) render destination exists and is not a directory"))
    end
    try
        Base.Filesystem.rename(temporary, destination)
    catch error
        if isdir(destination)
            return (:reused, _reuse_or_refuse(destination, proposed))
        end
        rethrow(error)
    end
    manifest = load_ar1_render_manifest(
        joinpath(destination, AR1_RENDER_MANIFEST_FILENAME))
    return (:computed, manifest)
end

"""
    render_ar1_contest(processed_path; output_root, completed_at, compress)

Authenticate one processed AR(1) artifact and atomically publish welfare
outcome, consumption-equivalent, and timing TeX tables. This renderer reads
only `processed_path`; it never calls a policy solver.
"""
function render_ar1_contest(
    processed_path::AbstractString;
    output_root::AbstractString=tables_dir("ar1_contest"),
    completed_at::DateTime=now(UTC),
    compress::Bool=true)

    # Authenticate before creating output state.
    processed = load_ar1_contest_welfare(processed_path)
    processed_metadata = _ar1_render_field(
        processed, :metadata, "processed artifact")
    methods = Symbol.(collect(_ar1_render_field(
        processed, :methods, "processed artifact")))
    panels = Symbol.(collect(_ar1_render_field(
        processed, :panels, "processed artifact")))
    panels == [:ar1] || throw(ArgumentError(
        "AR(1) renderer received an invalid panel"))
    scientific = _ar1_render_field(
        processed, :scientific_configuration, "processed artifact")
    model = _ar1_render_field(scientific, :model, "scientific_configuration")
    horizon = Int(_ar1_render_field(model, :horizon, "scientific_configuration.model"))
    Float64(_ar1_render_field(model, :rho, "scientific_configuration.model")) == 0.9 &&
        Float64(_ar1_render_field(model, :innovation_sigma,
            "scientific_configuration.model")) == 0.1 &&
        Float64(_ar1_render_field(model, :initial_income,
            "scientific_configuration.model")) == 1.0 ||
        throw(ArgumentError("AR(1) renderer calibration mismatch"))
    n_contests = IID._completion_status(processed).completed_contests
    n_paths = Int(_ar1_render_field(processed_metadata,
        :n_paths, "processed metadata"))
    timing_paths = Base.checked_mul(n_contests, n_paths)
    confidence_level = Float64(_ar1_render_field(processed_metadata,
        :confidence_level, "processed metadata"))
    configuration = _render_configuration(
        horizon, n_contests, n_paths, methods, confidence_level)
    source = _ar1_render_source_provenance(processed_path, processed)
    simulation = _ar1_render_field(
        processed, :simulation_metadata, "processed artifact")

    outcome_rows = IID._outcome_rows(
        processed, methods, panels)
    ce_rows = IID._ce_gap_rows(
        processed, methods, panels, horizon)
    timing_rows = IID._timing_rows(
        processed, methods, panels, timing_paths)
    IID._validate_rows(outcome_rows, ce_rows, timing_rows,
        methods, panels, confidence_level)
    completed_utc = _ar1_render_utc_string(completed_at)
    outcome_fingerprint = stable_fingerprint(outcome_rows)
    ce_fingerprint = stable_fingerprint(ce_rows)
    timing_fingerprint = stable_fingerprint(timing_rows)

    root = abspath(output_root)
    _validate_data_output(joinpath(root, "render-output.tex"))
    ispath(root) && !isdir(root) && throw(ArgumentError(
        "AR(1) render output root is not a directory: $root"))
    mkpath(root)
    destination = ar1_render_output_directory(root, String(_ar1_render_field(
        processed_metadata, :run_fingerprint, "processed metadata")))
    temporary = mktempdir(root;
        prefix=".ar1-contest-render-write-", cleanup=false)
    published = false
    try
        _render_outcome_table(joinpath(
            temporary, AR1_OUTCOME_TABLE_FILENAME), outcome_rows,
            source, outcome_fingerprint)
        _render_ce_gap_table(joinpath(
            temporary, AR1_CE_GAP_TABLE_FILENAME), ce_rows,
            source, ce_fingerprint)
        _render_timing_table(joinpath(
            temporary, AR1_TIMING_TABLE_FILENAME), timing_rows,
            n_contests, source, timing_fingerprint)
        tables = [
            _table_descriptor(:outcome_shares, AR1_OUTCOME_TABLE_FILENAME,
                completed_utc, outcome_fingerprint, temporary),
            _table_descriptor(:ce_gaps, AR1_CE_GAP_TABLE_FILENAME,
                completed_utc, ce_fingerprint, temporary),
            _table_descriptor(:timings, AR1_TIMING_TABLE_FILENAME,
                completed_utc, timing_fingerprint, temporary),
        ]
        source_identity_fingerprint = _source_identity(source)
        source_provenance_fingerprint = stable_fingerprint(source)
        render_configuration_fingerprint = stable_fingerprint(configuration)
        table_catalog_fingerprint = stable_fingerprint(tables)
        table_content_fingerprint = _table_content_fingerprint(tables)
        result_fingerprint = stable_fingerprint((;
            source_identity_fingerprint,
            render_configuration_fingerprint,
            outcome_rows_fingerprint=outcome_fingerprint,
            ce_gap_rows_fingerprint=ce_fingerprint,
            timing_rows_fingerprint=timing_fingerprint,
            table_content_fingerprint,
        ))
        metadata_without_authentication = (;
            artifact_schema=AR1_RENDER_CONTEST_SCHEMA_VERSION,
            status=:complete,
            completed_utc,
            source_status=:authenticated,
            source_artifact_schema=source.artifact_schema,
            source_identity_fingerprint,
            source_provenance_fingerprint,
            source_run_fingerprint=source.run_fingerprint,
            source_result_fingerprint=source.result_fingerprint,
            source_authentication_fingerprint=
                source.authentication_fingerprint,
            simulation_metadata_fingerprint=stable_fingerprint(simulation),
            render_configuration_fingerprint,
            outcome_rows_fingerprint=outcome_fingerprint,
            ce_gap_rows_fingerprint=ce_fingerprint,
            timing_rows_fingerprint=timing_fingerprint,
            table_catalog_fingerprint,
            table_content_fingerprint,
            result_fingerprint,
        )
        metadata = merge(metadata_without_authentication, (;
            authentication_fingerprint=
                _ar1_render_authentication(metadata_without_authentication),
        ))
        manifest_artifact = Dict{String,Any}(
            "metadata" => metadata,
            "source_provenance" => source,
            "simulation_metadata" => simulation,
            "render_configuration" => configuration,
            "outcome_rows" => outcome_rows,
            "ce_gap_rows" => ce_rows,
            "timing_rows" => timing_rows,
            "tables" => tables,
        )
        manifest_path = joinpath(temporary, AR1_RENDER_MANIFEST_FILENAME)
        _ar1_render_write_manifest(manifest_path, manifest_artifact; compress)
        load_ar1_render_manifest(manifest_path)
        status, restored = _publish_directory(
            destination, temporary, manifest_artifact)
        published = status === :computed
        table_paths = Dict(Symbol(table.id) =>
            joinpath(destination, String(table.filename))
            for table in restored["tables"])
        return (;
            status,
            output_directory=destination,
            manifest_path=joinpath(
                destination, AR1_RENDER_MANIFEST_FILENAME),
            table_paths,
            metadata=restored["metadata"],
            artifact=restored,
        )
    finally
        !published && ispath(temporary) &&
            rm(temporary; recursive=true)
    end
end
