const _AR1_RENDER_UTC_FORMAT = dateformat"yyyy-mm-ddTHH:MM:SS.sss"

_ar1_render_utc_string(value::DateTime) = Dates.format(value, _AR1_RENDER_UTC_FORMAT) * "Z"
_ar1_render_file_mtime_utc(path::AbstractString) =
    _ar1_render_utc_string(Dates.unix2datetime(stat(path).mtime))
_ar1_render_sha256_file(path::AbstractString) = bytes2hex(SHA.sha256(read(path)))

function _ar1_render_field(container, name::Symbol, location::AbstractString)
    if container isa NamedTuple
        hasproperty(container, name) || throw(ArgumentError(
            "$location is missing required field $name"))
        return getproperty(container, name)
    elseif container isa AbstractDict
        haskey(container, name) && return container[name]
        haskey(container, String(name)) && return container[String(name)]
    end
    throw(ArgumentError("$location is missing required field $name"))
end

_ar1_render_field(container, name::Symbol) = _ar1_render_field(container, name, "artifact")

function _ar1_render_method_label(method::Symbol)
    method === :ptd_sceq && return "PTD-SCEQ"
    method === :ptd_osa && return "PTD-OSA"
    method === :g2egm && return "G2EGM"
    throw(ArgumentError("unknown AR(1) method $method"))
end

_percent(value::Real) = @sprintf("%.2f", 100.0 * Float64(value))
_ar1_render_bps(value::Real) = @sprintf("%.3f", Float64(value))
_ar1_render_seconds(value::Real) = @sprintf("%.6f", Float64(value))

function _render_configuration(horizon::Int, n_contests::Int, n_paths::Int,
                               methods::Vector{Symbol},
                               confidence_level::Float64)
    methods == [:ptd_sceq, :ptd_osa, :g2egm] || throw(ArgumentError(
        "AR(1) render requires PTD-SCEQ, PTD-OSA, and G2EGM in order"))
    timing_paths = Base.checked_mul(n_contests, n_paths)
    timing_paths > 0 || throw(ArgumentError(
        "no successful configurations: consult run_audit.failures; welfare inference and per-path timing are unavailable"))
    return (;
        schema=AR1_RENDER_CONFIGURATION_SCHEMA_VERSION,
        role=:processed_ar1_contest_tables,
        source_role=:authenticated_processed_artifact_only,
        horizon,
        n_contests,
        n_paths,
        timing_paths,
        timing_average=:amortized_seconds_per_simulated_path,
        methods=Tuple(methods),
        panels=(:ar1,),
        calibration=(rho=0.9, sigma=0.1, initial_income=1.0),
        environment_label=AR1_ENVIRONMENT_LABEL,
        method_display=(
            ptd_sceq="PTD-SCEQ",
            ptd_osa="PTD-OSA",
            g2egm="G2EGM",
        ),
        paired_confidence_level=confidence_level,
        crra_normalization=:shifted,
        ce_orientation=:scale_method_b_to_match_method_a,
        ce_unit=:basis_points,
        paired_interval_endpoint_reference=:method_b_expected_utility,
        paired_interval_endpoint_kind=
            :plugin_ce_scaled_paired_utility_gap_interval,
        paired_interval_has_nominal_ce_coverage=false,
        paired_interval_endpoint_summary=:median_across_contests,
        paired_interval_summary_is_ci_for_median=false,
        implementation_file_sha256=_ar1_render_sha256_file(@__FILE__),
        table_files=(
            outcome_shares=AR1_OUTCOME_TABLE_FILENAME,
            ce_gaps=AR1_CE_GAP_TABLE_FILENAME,
            timings=AR1_TIMING_TABLE_FILENAME,
        ),
    )
end

function _ar1_render_trace_header(io, title::AbstractString, source,
                       row_fingerprint::AbstractString)
    println(io,
        "% Generated by Ptd.AR1; do not edit by hand.")
    println(io, "% Table: ", title)
    println(io, "% Processed run fingerprint: ", source.run_fingerprint)
    println(io, "% Processed result fingerprint: ",
        source.result_fingerprint)
    println(io, "% Processed file SHA-256: ", source.file_sha256)
    println(io, "% Row-data fingerprint: ", row_fingerprint)
end

function _render_outcome_table(path::AbstractString, rows, source,
                               row_fingerprint::String)
    open(path, "w") do io
        _ar1_render_trace_header(io, "AR(1) contest outcome shares", source,
            row_fingerprint)
        println(io, "\\begin{tabular}{llrrrrrr}")
        println(io, "\\toprule")
        println(io, "Environment & Method & Point win (\\%) & Resolved win (\\%) & Resolved loss (\\%) & MC unresolved (\\%) & Exact tie (\\%) & All unresolved (\\%) \\\\")
        println(io, "\\midrule")
        for row in rows
            println(io, AR1_ENVIRONMENT_LABEL, " & ",
                _ar1_render_method_label(row.method), " & ",
                _percent(row.point_winner_share), " & ",
                _percent(row.resolved_win_share), " & ",
                _percent(row.resolved_loss_share), " & ",
                _percent(row.mc_unresolved_share), " & ",
                _percent(row.point_tie_share), " & ",
                _percent(row.unresolved_share), " \\\\")
        end
        println(io, "\\bottomrule")
        println(io, "\\end{tabular}")
        IID._render_sample_note(io, first(rows).sample)
    end
    return path
end

function _render_ce_gap_table(path::AbstractString, rows, source,
                              row_fingerprint::String)
    confidence_levels = unique(Float64(row.confidence_level) for row in rows)
    length(confidence_levels) == 1 || throw(ArgumentError(
        "AR(1) CEG rows mix paired confidence levels"))
    confidence_percent = @sprintf("%.0f", 100.0 * only(confidence_levels))
    open(path, "w") do io
        _ar1_render_trace_header(io, "AR(1) contest CRRA consumption-equivalent gaps",
            source, row_fingerprint)
        println(io, "% Positive CEGs (in bps) favor method A; the scale is applied to method B to match method A.")
        println(io, "\\begin{tabular}{llrrrrrr}")
        println(io, "\\toprule")
        println(io, " & & \\multicolumn{3}{c}{CEG (basis points)} & \\multicolumn{3}{c}{Pairwise resolution (\\%)} \\\\")
        println(io, "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}")
        println(io, "Method A & Method B & P5 & Median & P95 & A resolved & B resolved & Unresolved \\\\")
        println(io, "\\midrule")
        println(io, "\\multicolumn{8}{l}{", AR1_ENVIRONMENT_LABEL, "} \\\\")
        for row in rows
            println(io, _ar1_render_method_label(row.method_a), " & ",
                _ar1_render_method_label(row.method_b), " & ",
                _ar1_render_bps(row.q05_bps), " & ",
                _ar1_render_bps(row.median_bps), " & ",
                _ar1_render_bps(row.q95_bps), " & ",
                _percent(row.method_a_resolved_share), " & ",
                _percent(row.method_b_resolved_share), " & ",
                _percent(row.pairwise_unresolved_share), " \\\\")
        end
        println(io, "\\bottomrule")
        println(io, "\\end{tabular}")
        println(io, "\\fnote{Notes: CEG is the consumption-equivalent gap; positive values favor method A. One basis point equals 0.01\\%. A or B is resolved when its paired $confidence_percent\\% utility-difference interval favors that method.}")
    end
    return path
end

function _render_timing_table(path::AbstractString, rows, n_contests::Int,
                              source, row_fingerprint::String)
    open(path, "w") do io
        _ar1_render_trace_header(io, "AR(1) contest timing totals", source,
            row_fingerprint)
        println(io, "\\begin{tabular}{llrrr}")
        println(io, "\\toprule")
        println(io, "Environment & Method & Total seconds ($n_contests tasks) & Amortized seconds/path & Julia threads \\\\")
        println(io, "\\midrule")
        for row in rows
            println(io, AR1_ENVIRONMENT_LABEL, " & ",
                _ar1_render_method_label(row.method), " & ",
                _ar1_render_seconds(row.total_seconds), " & ",
                _ar1_render_seconds(row.amortized_seconds_per_path), " & ",
                row.thread_count,
                " \\\\")
        end
        println(io, "\\bottomrule")
        println(io, "\\end{tabular}")
        IID._render_sample_note(io, first(rows).sample)
    end
    return path
end

function _ar1_paper_timing_summary(timing_path, contest;
    accuracy_path=nothing, require_production::Bool=true)
    isnothing(timing_path) && return nothing
    artifact = JLD2.load(timing_path, "artifact")
    if artifact.schema == AR1_PREFERENCE_TIMING_SCHEMA
        isnothing(accuracy_path) && throw(ArgumentError(
            "five-agent AR(1) timing requires its accuracy artifact path"))
        return load_ar1_preference_timing_summary(timing_path, accuracy_path;
            require_production)
    end
    summary = load_single_path_timing_summary(timing_path; required_panels=(:ar1,))
    case = summary.configurations[:ar1]
    scientific = _ar1_render_field(contest, :scientific_configuration)
    model = _ar1_render_field(scientific, :model)
    (case.return_rate, case.cash_floor, case.horizon, case.settings.rho,
        case.settings.sigma, case.settings.initial_income) ==
        (_ar1_render_field(model, :return_rate), _ar1_render_field(model, :cash_floor),
            _ar1_render_field(model, :horizon), _ar1_render_field(model, :rho),
            _ar1_render_field(model, :innovation_sigma), _ar1_render_field(model, :initial_income)) &&
        case.settings.quadrature_nodes == _ar1_render_field(
            _ar1_render_field(scientific, :quadrature), :nodes_per_dimension) ||
        throw(ArgumentError("single-path AR(1) timing calibration differs from the accuracy exercise"))
    case.settings.grid == _ar1_render_field(_ar1_render_field(scientific, :g2egm), :grids) ||
        throw(ArgumentError("single-path AR(1) timing grid differs from the accuracy exercise"))
    return summary
end

"""
Render AR(1) accuracy shares with optional five-agent single-thread timings.
Historical script-6 fixed-agent artifacts remain supported when supplied explicitly.
The exhibit-path argument is retained for compatibility. Missing timings are
shown as `not reported`. Set `include_sample_note=false` to suppress table notes.
"""
function render_ar1_paper_table(
    contest_path::AbstractString,
    exhibit_path::AbstractString;
    output_path::AbstractString=tables_dir("ar1_contest_summary.tex"),
    include_sample_note::Bool=true,
    timing_artifact_path::Union{Nothing,AbstractString}=nothing,
    require_production_timing::Bool=true)
    contest = load_ar1_contest_welfare(contest_path)
    IID._completion_status(contest).completed_contests == 0 &&
        return IID._render_no_success_table(contest, output_path)
    methods = Symbol.(collect(_ar1_render_field(contest, :methods)))
    panels = Symbol.(collect(_ar1_render_field(contest, :panels)))
    panels == [:ar1] || throw(ArgumentError(
        "the paper AR(1) table requires the single :ar1 panel"))
    outcome_rows = IID._outcome_rows(contest, methods, panels)
    outcomes = Dict(row.method => row for row in outcome_rows)
    timing = _ar1_paper_timing_summary(timing_artifact_path, contest;
        accuracy_path=contest_path, require_production=require_production_timing)

    destination = _validate_data_output(output_path)
    mkpath(dirname(destination))
    open(destination, "w") do io
        println(io, "% Generated by scripts/4_ar1.jl; do not edit.")
        println(io, "% Source authentication fingerprint: ",
            _ar1_render_field(_ar1_render_field(contest, :metadata), :authentication_fingerprint))
        IID._paper_timing_comments(io, timing)
        println(io, "\\begin{tabular}{lrrrr}")
        println(io, "\\toprule")
        println(io, "Method & \\makecell{Point win\\\\(\\%)} & \\makecell{Resolved win\\\\(\\%)} & \\makecell{Mean time\\\\(s)} & \\makecell{Median time\\\\(s)} \\\\")
        println(io, "\\midrule")
        for method in methods
            outcome = outcomes[method]
            mean_seconds = isnothing(timing) ? "not reported" :
                @sprintf("%.3f", timing.rows[(:ar1, method)].mean_total_seconds)
            median_seconds = isnothing(timing) ? "not reported" :
                @sprintf("%.3f", timing.rows[(:ar1, method)].median_total_seconds)
            println(io, _ar1_render_method_label(method), " & ",
                round(Int, 100 * outcome.point_winner_share), " & ",
                round(Int, 100 * outcome.resolved_win_share), " & ",
                mean_seconds, " & ", median_seconds, " \\\\")
        end
        println(io, "\\bottomrule")
        println(io, "\\end{tabular}")
        if include_sample_note
            IID._render_sample_note(io, first(outcome_rows).sample; timing=false)
            if !isnothing(timing) && hasproperty(timing, :configuration)
                println(io, "\\par\\smallskip{\\footnotesize \\emph{Timing:} Mean and median seconds across ",
                    timing.configuration.n_agents,
                    raw" agents with $\gamma\in\{1,1.5,2,2.5,3\}$, $\beta=0.98$, and initial cash 16. ",
                    "Each measurement includes a fresh solve and one common income path, using one Julia thread and one BLAS thread after warmup.}")
            else
                IID._render_single_path_note(io, timing, (:ar1,))
            end
        end
    end
    return destination
end

"""Render AR(1) CE quantiles from the authenticated heterogeneous contest."""
function render_ar1_ce_gap_table(contest_path::AbstractString;
    output_path::AbstractString=tables_dir(AR1_CE_GAP_TABLE_FILENAME))
    contest = load_ar1_contest_welfare(contest_path)
    IID._completion_status(contest).completed_contests == 0 &&
        return IID._render_no_success_table(contest, output_path)
    methods = Symbol.(collect(_ar1_render_field(contest, :methods)))
    panels = Symbol.(collect(_ar1_render_field(contest, :panels)))
    metadata = _ar1_render_field(contest, :metadata)
    model = _ar1_render_field(_ar1_render_field(contest, :scientific_configuration), :model)
    rows = IID._ce_gap_rows(contest, methods, panels,
        Int(_ar1_render_field(model, :horizon)))
    destination = _validate_data_output(output_path)
    mkpath(dirname(destination))
    return _render_ce_gap_table(destination, rows,
        IID._paper_table_source(contest_path, contest), stable_fingerprint(rows))
end

